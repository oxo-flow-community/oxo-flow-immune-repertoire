#!/usr/bin/env bash
# cutover_cluster_backend.sh — prepare production shards for the oxo-flow
# Slurm cluster backend (idempotent; dry-run unless --apply).
#
# Per shard this script:
#   1. verifies the shard directory and its groups.tsv
#   2. deploys the canonical workflow (sentinels included) from the repo
#   3. writes profiles/slurm.toml (backend=slurm, max_submitted=2, nodeN)
#   4. backfills completion sentinels for already-finished samples
#   5. runs the oxo-flow validate/lint gates and reports the plan size
#
# It does NOT stop the old supervisor or start the new drivers — those steps
# are ordered in docs/cutover_runbook.md.
#
# Usage (on node4 as wsx):
#   cutover_cluster_backend.sh                # dry run, all shards
#   cutover_cluster_backend.sh --apply        # write changes
#   cutover_cluster_backend.sh --apply --shards 1,2
set -uo pipefail

BASE=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
REPO=$BASE                      # canonical files live at the project root
OXO=oxo-flow
APPLY=0
SHARDS="1,2,3,4"
while [ "$#" -gt 0 ]; do
  case "$1" in
    --apply) APPLY=1 ;;
    --shards) SHARDS=${2:-$SHARDS}; shift ;;
    --shards=*) SHARDS=${1#--shards=} ;;
    *) ;;
  esac
  shift
done

[ -x "$OXO" ] || { echo "missing oxo-flow: $OXO" >&2; exit 1; }
# The repo carries two shapes of the same pipeline:
#   tcga-mixcr.oxoflow        test shape: inline [[sample_groups]] + test metadata
#   tcga-mixcr.shard.oxoflow  shard shape: metadata_file + sample_groups_file
# Deploying the test shape to a shard fails with "manifests/test_samples_metadata.tsv
# not found" — the shard variant is the one production runs.
SHARD_WF=$REPO/tcga-mixcr.shard.oxoflow
[ -f "$SHARD_WF" ] || { echo "missing shard workflow: $SHARD_WF" >&2; exit 1; }

if [ "$APPLY" -eq 1 ]; then MODE=APPLY; else MODE=DRY-RUN; fi
echo "cutover mode=$MODE shards=$SHARDS"

for n in ${SHARDS//,/ }; do
  DIR=$BASE/shards/shard$n
  echo
  echo "=== shard$n ($DIR) ==="
  [ -d "$DIR" ] || { echo "  MISSING shard directory — skipped"; continue; }
  [ -f "$DIR/manifests/groups.tsv" ] || { echo "  MISSING manifests/groups.tsv — skipped"; continue; }

  samples=$(awk -F'\t' 'NR>1 { s += split($2, a, ",") } END { print s + 0 }' "$DIR/manifests/groups.tsv")
  echo "  samples=$samples"

  if [ "$APPLY" -eq 1 ]; then
    cp "$SHARD_WF" "$DIR/tcga-mixcr.oxoflow"
  fi
  echo "  workflow: $(md5sum "$DIR/tcga-mixcr.oxoflow" 2>/dev/null | cut -d' ' -f1) (repo $(md5sum "$SHARD_WF" | cut -d' ' -f1))"

  mkdir -p "$DIR/profiles"
  PROFILE=$DIR/profiles/slurm.toml
  if [ "$APPLY" -eq 1 ]; then
    cat > "$PROFILE" <<EOF
# Generated by cutover_cluster_backend.sh — oxo-flow Slurm cluster backend.
# max_submitted=5 x 4 threads = 20 CPUs: the hard <=20 CPUs/node policy.
[cluster]
backend       = "slurm"
partition     = "workq"
walltime      = "12h"
max_submitted = 5
poll_interval = "20s"
extra_args    = ["--nodelist=node$n", "--export=ALL"]
EOF
  fi
  echo "  profile: $PROFILE $( [ -f "$PROFILE" ] && echo present || echo '(will be created)')"

  if [ "$APPLY" -eq 1 ]; then
    bash "$REPO/scripts/backfill_sentinels.sh" "$DIR/results" --apply
  else
    bash "$REPO/scripts/backfill_sentinels.sh" "$DIR/results"
  fi

  ( cd "$DIR" && "$OXO" validate tcga-mixcr.oxoflow 2>&1 | tail -1 )
  ( cd "$DIR" && "$OXO" lint tcga-mixcr.oxoflow 2>&1 | tail -1 )
done

echo
echo "done ($MODE). Next steps: docs/cutover_runbook.md"
